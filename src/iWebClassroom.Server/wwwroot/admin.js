const languageSelect = document.querySelector("#language");
const authPanel = document.querySelector("#auth-panel");
const workspace = document.querySelector("#admin-workspace");
const toast = document.querySelector("#toast");
const storedLanguage = localStorage.getItem("iwebclassroom-language");
const detectedLanguage = navigator.language?.toLowerCase().startsWith("es") ? "es" : navigator.language?.toLowerCase().startsWith("en") ? "en" : "pt-PT";
let language = storedLanguage || detectedLanguage;
let adminSession = sessionStorage.getItem("iwebclassroom-admin-session") || "";
let recoveryToken = sessionStorage.getItem("iwebclassroom-admin-recovery-token") || "";
let currentModel = null;

function t(key) { return translations[language]?.[key] || translations["pt-PT"][key] || key; }

function applyLanguage() {
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach(element => { element.textContent = t(element.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => { element.placeholder = t(element.dataset.i18nPlaceholder); });
  languageSelect.value = language;
  if (currentModel) render(currentModel);
}

async function applyInstallerLanguage() {
  if (storedLanguage) return;
  try {
    const response = await fetch("/api/v1/localization");
    if (!response.ok) return;
    const preference = await response.json();
    if (["pt-PT", "en", "es"].includes(preference.language)) {
      language = preference.language;
      applyLanguage();
    }
  } catch { /* The browser language remains the fallback. */ }
}

function notify(message) {
  toast.textContent = message;
  toast.classList.add("visible");
  window.clearTimeout(notify.timer);
  notify.timer = window.setTimeout(() => toast.classList.remove("visible"), 3500);
}

async function api(path, options = {}) {
  const authenticationHeader = adminSession
    ? { "X-Admin-Session": adminSession }
    : recoveryToken ? { "X-Admin-Token": recoveryToken } : {};
  const response = await fetch(path, {
    ...options,
    headers: { "Content-Type": "application/json", ...authenticationHeader, ...(options.headers || {}) }
  });
  const body = await response.json().catch(() => ({}));
  if (response.status === 401) {
    sessionStorage.removeItem("iwebclassroom-admin-session");
    sessionStorage.removeItem("iwebclassroom-admin-recovery-token");
    adminSession = "";
    recoveryToken = "";
    workspace.hidden = true;
    authPanel.hidden = false;
    throw new Error(t("loginFailed"));
  }
  if (!response.ok) throw new Error(body.error || body.detail || t("requestFailed"));
  return body;
}

function statusLabel(status) { return t(status) || status; }

function render(model) {
  currentModel = model;
  const configuration = model.configuration;
  const cloud = model.cloud;
  document.querySelector("#require-https").value = String(configuration.security.require_https);
  document.querySelector("#lesson-duration").value = configuration.classroom.default_lesson_duration_minutes;
  document.querySelector("#frame-size").value = configuration.classroom.maximum_frame_bytes;
  document.querySelector("#frame-interval").value = configuration.classroom.minimum_frame_interval_milliseconds;
  document.querySelector("#allowed-apps").value = configuration.classroom.allowed_application_ids.join("\n");
  document.querySelector("#update-enabled").value = String(configuration.update.enabled);
  document.querySelector("#update-interval").value = configuration.update.check_interval_hours;
  document.querySelector("#manifest-url").value = configuration.update.manifest_url;
  document.querySelector("#signer-thumbprint").value = configuration.update.signer_thumbprint;

  const badge = document.querySelector("#cloud-badge");
  badge.textContent = statusLabel(cloud.status);
  badge.className = `status-pill ${cloud.connected ? "success" : cloud.status === "error" ? "failure" : ""}`;
  const rows = [
    [t("school"), cloud.schoolName || "—"], [t("serverId"), cloud.serverId || "—"],
    [t("instance"), cloud.instanceUid], [t("revision"), cloud.configurationRevision],
    [t("lastSync"), cloud.lastSyncUtc ? new Date(cloud.lastSyncUtc).toLocaleString(language) : t("never")],
    [t("cloudUrl"), cloud.cloudUrl]
  ];
  document.querySelector("#cloud-details").innerHTML = rows.map(([label, value]) =>
    `<div><span>${escapeHtml(label)}</span><strong>${escapeHtml(String(value))}</strong></div>`).join("") +
    (cloud.lastError ? `<p class="error-message">${escapeHtml(cloud.lastError)}</p>` : "");
  document.querySelector("#cloud-connect-form").hidden = cloud.connected;
  document.querySelector("#sync-now").hidden = !cloud.connected;
  document.querySelector("#disconnect-cloud").hidden = !cloud.connected;

  const licenseState = model.license || {};
  const licensePayload = licenseState.license?.payload;
  const licenseStatus = licensePayload?.status || "missing";
  const licenseBadge = document.querySelector("#license-badge");
  licenseBadge.textContent = t(licenseStatus) || licenseStatus;
  licenseBadge.className = `status-pill ${licenseStatus === "active" ? "success" : "failure"}`;
  const licenseRows = licensePayload ? [
    [t("plan"), licensePayload.plan || "—"],
    [t("maxDevices"), licensePayload.limits?.max_devices ?? "—"],
    [t("maxClassrooms"), licensePayload.limits?.max_classrooms ?? "—"],
    [t("leaseExpires"), formatDate(licensePayload.lease_expires_at)],
    [t("offlineGrace"), formatDate(licensePayload.offline_grace_until)],
    [t("licenseReceived"), formatDate(licenseState.receivedAtUtc)]
  ] : [[t("licenseUnavailable"), "—"]];
  document.querySelector("#license-details").innerHTML = licenseRows.map(([label, value]) =>
    `<div><span>${escapeHtml(label)}</span><strong>${escapeHtml(String(value))}</strong></div>`).join("");
}

function formatDate(value) {
  return value ? new Date(value).toLocaleString(language) : "—";
}

function escapeHtml(value) {
  const element = document.createElement("span");
  element.textContent = value;
  return element.innerHTML;
}

async function load() {
  const model = await api("/api/v1/settings");
  authPanel.hidden = true;
  workspace.hidden = false;
  render(model);
}

document.querySelector("#auth-form").addEventListener("submit", async event => {
  event.preventDefault();
  const submitButton = event.currentTarget.querySelector("button[type='submit']");
  submitButton.disabled = true;
  submitButton.textContent = t("connecting");
  try {
    const response = await fetch("/api/v1/admin/login", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        email: document.querySelector("#login-email").value.trim(),
        password: document.querySelector("#login-password").value
      })
    });
    const model = await response.json().catch(() => ({}));
    if (!response.ok) {
      const localizedError = model.code ? translations[language]?.[model.code] : null;
      throw new Error(localizedError || model.error || model.detail || t("requestFailed"));
    }
    adminSession = model.sessionToken;
    recoveryToken = "";
    sessionStorage.setItem("iwebclassroom-admin-session", adminSession);
    sessionStorage.removeItem("iwebclassroom-admin-recovery-token");
    document.querySelector("#login-password").value = "";
    authPanel.hidden = true;
    workspace.hidden = false;
    render(model);
    notify(t("connectedTo"));
  } catch (error) { notify(error.message); }
  finally {
    submitButton.disabled = false;
    submitButton.textContent = t("enter");
  }
});

