function t(key, values = {}) {
  let value = translations[state.language]?.[key] || translations["pt-PT"][key] || key;
  Object.entries(values).forEach(([name, replacement]) => { value = value.replace(`{${name}}`, replacement); });
  return value;
}

function applyLanguage() {
  document.documentElement.lang = state.language;
  document.querySelector("#language").value = state.language;
  document.querySelectorAll("[data-i18n]").forEach(element => element.textContent = t(element.dataset.i18n));
  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => element.placeholder = t(element.dataset.i18nPlaceholder));
  document.querySelectorAll("[data-i18n-aria-label]").forEach(element => element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel)));
  if (state.agents.length) renderOverview(); else updateCount();
}

async function applyInstallerLanguage() {
  if (storedLanguage) return;
  try {
    const response = await fetch("/api/v1/localization");
    if (!response.ok) return;
    const preference = await response.json();
    if (["pt-PT", "en", "es"].includes(preference.language)) {
      state.language = preference.language;
      applyLanguage();
    }
  } catch { /* The browser language remains the fallback. */ }
}

async function api(path, options = {}) {
  const { keepAccessFlow = false, ...fetchOptions } = options;
  const response = await fetch(path, { ...fetchOptions, headers: { "Content-Type": "application/json", "Accept-Language": state.language, ...(state.session ? { "X-Teacher-Session": state.session } : {}), ...(fetchOptions.headers || {}) } });
  if (response.status === 401) { if (!keepAccessFlow) logout(); throw new Error(t("invalidCode")); }
  if (!response.ok) {
    const body = await response.text();
    let detail = body;
    try {
      const parsed = JSON.parse(body);
      if (parsed.code === "invalid_email") detail = t("invalidEmail");
      else if (parsed.code === "invalid_access_code") detail = t("invalidCode");
      else if (response.status === 429) detail = t("tooManyRequests");
      else if (parsed.code === "teacher_access_unavailable" || parsed.code === "mail_delivery_failed") detail = t("accessUnavailable");
      else detail = parsed.error || parsed.detail || parsed.message || body;
    } catch { /* plain response */ }
    throw new Error(detail || `Erro ${response.status}`);
  }
  return response.status === 204 ? null : response.json();
}

