function t(key, values = {}) {
  let value = translations[state.language]?.[key] || translations["pt-PT"][key] || key;
  Object.entries(values).forEach(([name, replacement]) => { value = value.replace(`{${name}}`, replacement); });
  return value;
}

function applyLanguage() {
  document.documentElement.lang = state.language;
  document.querySelector("#language").value = state.language;
  document.querySelectorAll("[data-i18n]").forEach(element => element.textContent = t(element.dataset.i18n));
  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => element.placeholder = t(element.dataset.i18nPlaceholder));
  if (state.agents.length) renderOverview(); else updateCount();
}

async function applyInstallerLanguage() {
  if (storedLanguage) return;
  try {
    const response = await fetch("/api/v1/localization");
    if (!response.ok) return;
    const preference = await response.json();
    if (["pt-PT", "en", "es"].includes(preference.language)) {
      state.language = preference.language;
      applyLanguage();
    }
  } catch { /* The browser language remains the fallback. */ }
}

async function api(path, options = {}) {
  const response = await fetch(path, { ...options, headers: { "Content-Type": "application/json", "Accept-Language": state.language, ...(state.session ? { "X-Teacher-Session": state.session } : {}), ...(options.headers || {}) } });
  if (response.status === 401) { logout(); throw new Error(t("invalidCode")); }
  if (!response.ok) {
    const body = await response.text();
    let detail = body;
    try {
      const parsed = JSON.parse(body);
      if (parsed.code === "invalid_email") detail = t("invalidEmail");
      else if (parsed.code === "invalid_access_code") detail = t("invalidCode");
      else if (response.status === 429) detail = t("tooManyRequests");
      else if (parsed.code === "teacher_access_unavailable" || parsed.code === "mail_delivery_failed") detail = t("accessUnavailable");
      else detail = parsed.error || parsed.detail || parsed.message || body;
    } catch { /* plain response */ }
    throw new Error(detail || `Erro ${response.status}`);
  }
  return response.status === 204 ? null : response.json();
}

function toast(message) {
  elements.toast.textContent = message; elements.toast.classList.add("visible");
  window.setTimeout(() => elements.toast.classList.remove("visible"), 3400);
}

function logout() {
  state.session = ""; state.teacher = null; state.pendingEmail = ""; sessionStorage.removeItem("teacher-session");
  elements.code.value = ""; elements.verifyForm.hidden = true; elements.requestForm.hidden = false;
  elements.authPanel.hidden = false; elements.workspace.hidden = true;
}
function currentLesson() {
  return elements.roomMode.value === "temporary"
    ? state.lessons.find(lesson => lesson.isTemporary && lesson.teacherId === state.teacher?.teacherId)
    : state.lessons.find(lesson => !lesson.isTemporary && lesson.roomId === elements.room.value);
}
function selectedIds() { return [...elements.agents.querySelectorAll("input:checked")].map(input => input.value); }
function escapeHtml(value) { const node = document.createElement("span"); node.textContent = value ?? ""; return node.innerHTML; }

async function loadOverview() {
  const overview = await api("/api/v1/teacher/overview");
  state.agents = overview.agents || [];
  state.lessons = overview.lessons || [];
  state.fixedRooms = overview.fixedRooms || [];
  state.teacher = overview.teacher || state.teacher;
  if (!state.durationInitialized && overview.defaultLessonDurationMinutes) {
    const duration = String(overview.defaultLessonDurationMinutes);
    if (![...elements.duration.options].some(option => option.value === duration)) {
      elements.duration.add(new Option(`${duration} min`, duration));
    }
    elements.duration.value = duration;
    state.durationInitialized = true;
  }
  renderOverview();
}

function renderOverview() {
  const previousRoom = elements.room.value;
  const roomMap = new Map(state.fixedRooms.map(room => [room.code, room.name]));
  state.agents.filter(agent => agent.role === 0 && !agent.isShared).forEach(agent => { if (!roomMap.has(agent.classroomId)) roomMap.set(agent.classroomId, agent.classroomId); });
  const rooms = [...roomMap.entries()].sort((a, b) => a[1].localeCompare(b[1]));
  elements.room.innerHTML = rooms.length ? rooms.map(([code, name]) => `<option value="${escapeHtml(code)}">${escapeHtml(name)}</option>`).join("") : `<option value="">${t("noRooms")}</option>`;
  elements.room.value = rooms.some(([code]) => code === previousRoom) ? previousRoom : (rooms[0]?.[0] || "");

  const teachers = state.agents.filter(agent => agent.role === 1).sort((a, b) => a.displayName.localeCompare(b.displayName));
  elements.teacher.innerHTML = teachers.length
    ? teachers.map(agent => `<option value="${agent.agentId}">${escapeHtml(agent.displayName)} · ${escapeHtml(agent.classroomId)} · ${t(agent.isOnline ? "online" : "offline")}</option>`).join("")
    : `<option value="">${t("noTeachers")}</option>`;

  const lesson = currentLesson();
  const ownedLesson = Boolean(lesson && lesson.teacherId === state.teacher?.teacherId);
  if (lesson) elements.teacher.value = lesson.teacherAgentId;
  elements.teacher.disabled = Boolean(lesson);
  elements.duration.disabled = Boolean(lesson);
  elements.start.hidden = Boolean(lesson);
  elements.end.hidden = !ownedLesson;
  const temporary = elements.roomMode.value === "temporary";
  document.querySelector("#fixed-room-field").hidden = temporary;
  document.querySelector("#temporary-room-field").hidden = !temporary;
  elements.start.disabled = (!temporary && !rooms.length) || !teachers.length;
  document.querySelector("#teacher-welcome").textContent = state.teacher ? t("teacherWelcome", { name: state.teacher.displayName }) : t("lessonReady");
  setActionsEnabled(ownedLesson);
  renderLessonStatus(lesson);
  renderAgents(lesson);
}

function renderLessonStatus(lesson) {
  if (!lesson) {
    elements.lessonStatus.className = "lesson-status card ready";
    elements.lessonStatus.textContent = state.agents.length ? t("lessonReady") : t("noRooms");
    return;
  }
  const students = state.agents.filter(agent => lesson.memberAgentIds.includes(agent.agentId) && agent.role === 0);
  const online = students.filter(agent => agent.isOnline).length;
  const time = new Intl.DateTimeFormat(state.language, { hour: "2-digit", minute: "2-digit" }).format(new Date(lesson.expiresAtUtc));
  elements.lessonStatus.className = "lesson-status card active";
  const base = t("lessonActive", { room: lesson.roomName || lesson.roomId, online, total: students.length, time });
  elements.lessonStatus.textContent = lesson.isTemporary && lesson.joinCode ? `${base} · ${t("temporaryPin", { pin: lesson.joinCode })}` : base;
}

function renderAgents(lesson) {
  const participantNames = new Map((lesson?.participants || []).map(participant => [participant.agentId, participant.studentName]));
  const students = lesson?.isTemporary
    ? state.agents.filter(agent => agent.role === 0 && lesson.memberAgentIds.includes(agent.agentId))
    : state.agents.filter(agent => agent.role === 0 && !agent.isShared && agent.classroomId === elements.room.value);
  if (lesson?.lessonId !== state.renderedLessonId) {
    state.selected = new Set(students.filter(agent => agent.isOnline && lesson?.memberAgentIds.includes(agent.agentId)).map(agent => agent.agentId));
    state.renderedLessonId = lesson?.lessonId || null;
  }
  const availableIds = new Set(students.filter(agent => agent.isOnline && lesson?.memberAgentIds.includes(agent.agentId)).map(agent => agent.agentId));
  state.selected = new Set([...state.selected].filter(id => availableIds.has(id)));
  elements.agents.innerHTML = students.length ? students.map(agent => {
    const available = Boolean(lesson?.memberAgentIds.includes(agent.agentId)) && agent.isOnline;
    const studentName = participantNames.get(agent.agentId);
    const visibleName = studentName || agent.displayName;
    const metadata = studentName ? `${t("computer")}: ${agent.displayName} · ${t(agent.isOnline ? "online" : "offline")}` : `${t("student")} · ${t(agent.isOnline ? "online" : "offline")}`;
    return `<label class="agent ${available ? "available" : ""}">
      <input type="checkbox" value="${agent.agentId}" ${state.selected.has(agent.agentId) ? "checked" : ""} ${available ? "" : "disabled"} aria-label="${escapeHtml(visibleName)}">
      <span class="status-dot ${agent.isOnline ? "online" : ""}"></span>
      <span class="agent-details"><span class="agent-name">${escapeHtml(visibleName)}</span><span class="agent-meta">${escapeHtml(metadata)}</span></span>
    </label>`;
  }).join("") : `<div class="empty">${t("noAgents")}</div>`;
  elements.agents.querySelectorAll("input").forEach(input => input.addEventListener("change", () => {
    if (input.checked) state.selected.add(input.value); else state.selected.delete(input.value);
    updateCount();
  }));
  updateCount();
}

function updateCount() { const count = selectedIds().length; elements.count.textContent = `${count} ${count === 1 ? t("selectedOne") : t("selectedMany")}`; }
function setActionsEnabled(enabled) {
  document.querySelectorAll("#lesson-actions button, #lesson-actions textarea").forEach(element => { element.disabled = !enabled; });
  document.querySelector("#lesson-actions").classList.toggle("disabled", !enabled);
}

async function send(kind, payload, targets = selectedIds()) {
  const lesson = currentLesson();
  if (!lesson) { toast(t("startFirst")); return; }
  if (!targets.length) { toast(t("selectComputer")); return; }
  await api(`/api/v1/lessons/${lesson.lessonId}/commands`, { method: "POST", body: JSON.stringify({ targetAgentIds: targets, kind, payload }) });
  toast(t("actionSent"));
}

elements.requestForm.addEventListener("submit", async event => {
  event.preventDefault();
  try {
    state.pendingEmail = elements.email.value.trim();
    await api("/api/v1/teacher/access/request", { method: "POST", body: JSON.stringify({ email: state.pendingEmail }) });
    elements.accessEmail.textContent = state.pendingEmail; elements.requestForm.hidden = true; elements.verifyForm.hidden = false; elements.code.focus();
    toast(t("codeRequested"));
  } catch (error) { toast(error.message); }
});

elements.verifyForm.addEventListener("submit", async event => {
  event.preventDefault();
  try {
    const login = await api("/api/v1/teacher/access/verify", { method: "POST", body: JSON.stringify({ email: state.pendingEmail, code: elements.code.value.trim() }) });
    state.session = login.sessionToken; sessionStorage.setItem("teacher-session", state.session); elements.code.value = "";
    await loadOverview(); elements.authPanel.hidden = true; elements.workspace.hidden = false;
  } catch (error) { toast(error.message); }
});

